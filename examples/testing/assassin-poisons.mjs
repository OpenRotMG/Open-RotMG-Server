import {readFile,writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {randomUUID} from 'node:crypto';
import assert from 'node:assert/strict';
const root=process.argv[process.argv.indexOf('--run-dir')+1];
export const fixture={class:0x320,level:20,seed:770,world:'kitchen',position:{x:13.5,y:40.5},equipment:[-1,0xaa3,-1,-1],backpack:[0xb2a,-1,-1,-1,-1,-1,-1,-1],stats:[720,252,60,25,75,75,40,60]};
export async function run(game){
  const before=await game.inspect(),initial=await game.observe(),boss=before.diagnostic.entities.find(e=>e.kind===0x926);assert(boss);
  await game.act({keys:[],duration_ms:500},{name:'assassin-before',when:()=>true});
  const ready=await game.observe();
  await game.act({keys:[' '],duration_ms:250,target:{entity:boss.id,camera_angle:-Math.PI/4,fire:false}});
  const thrown=await game.inspect();
  game.check('T0 poison spends mana once',thrown.view.character.mp>=ready.character.mp-30&&thrown.view.character.mp<ready.character.mp-20);
  game.check('throw does not damage immediately',thrown.diagnostic.entities.find(e=>e.id===boss.id)?.hp===boss.hp);
  await game.act({keys:[],duration_ms:7000},{name:'assassin-poison',when:v=>v.game_ms>=thrown.view.time_ms+2500});
  const poisoned=await game.inspect(),hurt=poisoned.diagnostic.entities.find(e=>e.id===boss.id);
  await writeFile(join(root,'poison-observations.json'),JSON.stringify({before,thrown,poisoned},null,2));
  game.check('T0 completes exactly 150 poison damage',hurt?.hp===boss.hp-150);
  game.check('no dagger shots were used',(await game.observe()).verification.shots===initial.verification.shots);
  await game.act({keys:[],duration_ms:350,drag:{from:{x:634,y:428},to:{x:678,y:385}}});
  const equipped=await game.observe();
  game.check('native inventory equips T6 poison',equipped.character.items[1]===0xb2a);
  game.check('T6 grants two vitality and wisdom',equipped.character.stats.vitality===42&&equipped.character.stats.wisdom===62);
  await game.act({keys:[' '],duration_ms:250,target:{entity:boss.id,camera_angle:-Math.PI/4,fire:false}});
  const second=await game.observe();
  game.check('T6 spends one 110 MP cost',second.character.mp>=equipped.character.mp-110&&second.character.mp<equipped.character.mp-100);
  await game.act({keys:[],duration_ms:4500},{name:'assassin-victory',when:v=>v.verification.kills>initial.verification.kills});
  const victory=await game.inspect(),credited=await game.observe();
  game.check('T6 poison defeats Bonegrind without weapon fire',!victory.diagnostic.entities.some(e=>e.id===boss.id)&&credited.verification.kills>initial.verification.kills&&credited.verification.shots===initial.verification.shots);
  await game.act({keys:[],duration_ms:4000});
  game.check('poison kills are not credited again',(await game.observe()).verification.kills===credited.verification.kills);
  const config=JSON.parse(await readFile(join(root,'native.json'),'utf8'));
  const token=(await readFile(join(config.state,'control.token'),'utf8')).trim();
  const response=await fetch(config.origin+'/dev/testing',{method:'POST',headers:{Authorization:'Bearer '+token,'Content-Type':'application/json'},body:JSON.stringify({id:randomUUID(),command:{op:'cheat',actor:game.actor,change:{kind:'vitals',hp:600,mp:0}}}),signal:AbortSignal.timeout(10000)});
  const receipt=await response.json();assert(response.ok&&receipt.status==='succeeded',JSON.stringify(receipt));
  const poor=await game.observe();
  await game.act({keys:[' '],duration_ms:250});const denied=await game.observe();
  game.check('zero MP rejects poison without a new cooldown',denied.character.mp>=0&&denied.character.mp<10&&denied.character.ability_ready_ms===poor.character.ability_ready_ms);
  game.check('same living Assassin retains T6',denied.lifecycle.alive&&denied.session.character===before.view.session.character&&denied.character.items[1]===0xb2a);
  await writeFile(join(root,'poison-observations.json'),JSON.stringify({before,initial,thrown,poisoned,equipped,second,victory,credited,denied},null,2));
}
