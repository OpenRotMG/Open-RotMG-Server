pub(crate) const ROOTS: &[u16] = &[0x678, 0x925, 0x935, 0x941, 0xd50, 0xd54, 0xe37];
pub(crate) fn owner(kind: u16) -> anyhow::Result<u16> {
    Ok(match kind {
        0x678..=0x67c => 0x678,
        0x925 | 0x65a..=0x65e => 0x925,
        0x935 => 0x935,
        0x941..=0x943 => 0x941,
        0xd50..=0xd53 => 0xd50,
        0xd54..=0xd55 => 0xd54,
        0xe37 | 0xe38 | 0xe39 | 0xe3b | 0xe3c | 0xe3d | 0xe4f => 0xe37,
        _ => anyhow::bail!("landmark identity {kind:#x} has no authored landmark owner"),
    })
}
#[test]
fn landmark_owner_refuses_unselected_identity_with_context() {
    assert_eq!(owner(0x67c).unwrap(), 0x678);
    assert!(format!("{:#}", owner(0x600).unwrap_err()).contains("0x600"));
}
