pub(super) fn patch(data: &mut [u8]) -> Result<usize> {
    let positions: Vec<_> = data
        .windows(METHOD.len())
        .enumerate()
        .filter_map(|(i, bytes)| (bytes == METHOD).then_some(i))
        .collect();
    ensure!(
        positions.len() <= 1,
        "ambiguous remote interpolation method"
    );
    ensure!(
        CODE.len() <= 469,
        "remote interpolation patch exceeds method"
    );
    if let Some(&offset) = positions.first() {
        // Stop at the received destination during stalls, not beyond it: https://github.com/OpenRotMG/Open-RotMG-Client/blob/4d171652c410fe4da26065b79441d1c0c2da9f94/client.swf (GameObject.update).
        let body = &mut data[offset + 6..offset + 6 + 469];
        body.fill(0x02);
        body[..CODE.len()].copy_from_slice(CODE);
    }
    Ok(positions.len())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn interpolation_patch_requires_exact_unique_body_and_preserves_layout() {
        let original = [b"prefix".as_slice(), METHOD, b"suffix".as_slice()].concat();
        let mut patched = original.clone();
        assert_eq!(patch(&mut patched).unwrap(), 1);
        assert_eq!(patched.len(), original.len());
        assert_eq!(&patched[..12], &original[..12]);
        assert_eq!(&patched[12..12 + CODE.len()], CODE);
        assert!(
            patched[12 + CODE.len()..12 + 469]
                .iter()
                .all(|b| *b == 0x02)
        );
        assert_eq!(&patched[12 + 469..], &original[12 + 469..]);
        assert_eq!(patch(&mut patched).unwrap(), 0);
        let mut duplicate = METHOD.repeat(2);
        assert!(patch(&mut duplicate).is_err());
        assert_eq!(duplicate, METHOD.repeat(2));
        for i in 0..METHOD.len() {
            let mut changed = METHOD.to_vec();
            changed[i] ^= 1;
            let before = changed.clone();
            assert_eq!(patch(&mut changed).unwrap(), 0);
            assert_eq!(changed, before);
        }
    }
}
